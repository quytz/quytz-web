class LocalizationService {
  constructor() {
    this.currentLanguage = "vi";
  }

  setLanguage(lang) {
    if (DICTIONARIES[lang]) {
      this.currentLanguage = lang;
      document.documentElement.lang = lang;
    }
  }

  t(key, ...args) {
    const dict = DICTIONARIES[this.currentLanguage] || DICTIONARIES.vi;
    let str = dict[key] || DICTIONARIES.vi[key] || key;
    if (args.length > 0) {
      args.forEach(arg => {
        str = str.replace("%s", arg).replace("%@", arg);
      });
    }
    return str;
  }
}

export const i18n = new LocalizationService();
